"""
nvdiffrast-based renderer for the MegaPose 3D models (Google Scanned Objects and
ShapeNetCoreV2). For each object it samples Hammersley viewpoints on a sphere and renders
either base color (shading_mode='texture') or world-space normals (shading_mode='normal').

The base-color pass writes a transforms.json per object; the normal pass reuses those same
poses by reading transforms.json from the matching renders3-color folder, so run the
'texture' pass before the 'normal' pass.

GSO vs ShapeNet are auto-detected from mesh_root (the ShapeNet branch is used when the path
contains 'shapenetcorev2'); they differ in mesh folder layout and normalization.
"""

